export function obtenerEjercicio(id) {
  return EJERCICIOS_CATALOGO[id] || null;
}

export function modificacionesEjercicio(id) {
  return MODIFICACIONES[id] || { facil: 'Reduce el rango o el ritmo', fuerte: 'Aumenta el rango o el ritmo' };
}

export function nombreEjercicio(id) {
  return obtenerEjercicio(id)?.nombre || id.replace('_', ' ');
}

export function esDeTiempo(id) {
  return obtenerEjercicio(id)?.modo === 'tiempo';
}

export function consignaEjercicio(id) {
  const ejercicio = obtenerEjercicio(id);
  if (!ejercicio) return { consigna: 'Sostén', consignaAyuda: 'Mantén la posición' };
  return {
    consigna: ejercicio.consigna || 'Sostén',
    consignaAyuda: ejercicio.consignaAyuda || 'Mantén la posición',
  };
}

// Intensidad inferida por grupo muscular, usada por el motor de música en
// el formato 'express' (clases sin secciones ni campo intensidad).
const INTENSIDAD_POR_GRUPO = Object.freeze({
  cardio: 'alta',
  piernas: 'media',
  pecho: 'media',
  core: 'media',
  espalda: 'media',
  glúteos: 'media',
  movilidad: 'suave',
});

export function intensidadEjercicio(id) {
  const ejercicio = obtenerEjercicio(id);
  if (!ejercicio) return 'media';
  const porGrupo = INTENSIDAD_POR_GRUPO[ejercicio.grupo];
  if (porGrupo) return porGrupo;
  if (ejercicio.modo === 'tiempo') return 'media';
  return 'media';
}
